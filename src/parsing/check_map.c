#include "parsing.h"

static int	is_walkable(char c)
{
	return (c == '0' || c == 'N' || c == 'S' || c == 'E' || c == 'W');
}

/*
** Проверяет ОДНУ клетку карты: если это проходимая клетка ('0' или
** буква спавна), ни один из её четырёх соседей не должен резолвиться
** в пробел. get_map_char() уже трактует одинаково и настоящий пробел
** внутри данных карты, и координату за пределами данных карты (за
** последней строкой, за концом конкретной, возможно короткой,
** строки), поэтому одной этой проверки достаточно, чтобы поймать
** "утечку" карты наружу.
*/
static void	check_cell_closed(t_cub *cub, int y, int x)
{
	char	c;

	c = get_map_char(cub, y, x);
	if (!is_walkable(c))
		return ;
	if (get_map_char(cub, y - 1, x) == ' '
		|| get_map_char(cub, y + 1, x) == ' '
		|| get_map_char(cub, y, x - 1) == ' '
		|| get_map_char(cub, y, x + 1) == ' ')
		parse_error(cub, "map is not closed by walls");
}

/*
** Проходит по КАЖДОЙ клетке КАЖДОЙ строки карты (используя реальную
** длину конкретной строки, чтобы корректно поддерживать "рваные" /
** irregular карты) и проверяет её замкнутость.
**
** В отличие от прежней версии (flood fill, стартующий только от
** позиции игрока), эта проверка не зависит от достижимости клетки
** от игрока: проверяется абсолютно вся карта. Поэтому отдельная,
** недостижимая от игрока область '0', открытая наружу, тоже будет
** найдена и отклонена — как и требует subject ("вся карта должна
** быть окружена стенами", а не только область вокруг игрока).
**
** Как приятный побочный эффект: больше не нужен malloc под стек /
** visited-массив flood fill'а, поэтому эта проверка не может сама
** по себе давать утечки или падать по malloc failure.
*/
void	check_map_closed(t_cub *cub)
{
	int	y;
	int	x;

	y = 0;
	while (y < cub->map_h)
	{
		x = 0;
		while (x < (int)ft_strlen(cub->map[y]))
		{
			check_cell_closed(cub, y, x);
			x++;
		}
		y++;
	}
}
